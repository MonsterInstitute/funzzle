#!/usr/bin/env node
/**
 * Regenerates lib/games/words/data/*.ts from the raw word lists.
 *
 *   node scripts/build-wordlists.mjs
 *
 * Raw downloads are cached under scripts/.wordlists-cache/ (gitignored) and
 * checked against pinned SHA-256 hashes, so the output is reproducible. See
 * lib/games/words/SOURCES.md for sources and licenses.
 *
 * Tiers (lowercase a-z only, 3-15 letters, blocklist removed):
 *   common = SCOWL American English, size <= 35   -> isCommon / answers
 *   valid  = SCOWL American English, size <= 50   -> isWord / bonus words
 *   guess5 = valid 5-letter words + ENABLE 5-letter words -> Funzzle Word guesses
 *   answers5 = common 5-letter words minus plain inflections (-s, -es, -ed, -ing)
 *
 * Needs Node >= 22.18 (imports the TypeScript blocklist with type stripping).
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import zlib from "node:zlib";
import { isBlocked } from "../lib/games/words/blocklist.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CACHE = path.join(ROOT, "scripts/.wordlists-cache");
const OUT = path.join(ROOT, "lib/games/words/data");

const SCOWL_VERSION = "2020.12.07";
const SOURCES = {
  scowl: {
    url: `https://downloads.sourceforge.net/wordlist/scowl-${SCOWL_VERSION}.tar.gz`,
    file: `scowl-${SCOWL_VERSION}.tar.gz`,
    sha256: "5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc",
  },
  enable: {
    url: "https://norvig.com/ngrams/enable1.txt",
    file: "enable1.txt",
    sha256: "61ba1392a5b6199dd161fae7b483cd262fb8a88c0d49bd2c9ecb6753e755697f",
  },
};
const SCOWL_SIZES = [10, 20, 35, 40, 50];
const COMMON_MAX = 35;
const VALID_MAX = 50;
const MIN_LEN = 3;
const MAX_LEN = 15;

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

async function fetchCached({ url, file, sha256: want }) {
  const dest = path.join(CACHE, file);
  if (!fs.existsSync(dest)) {
    console.log(`downloading ${url}`);
    const res = await fetch(url, { redirect: "follow" });
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  }
  const got = sha256(fs.readFileSync(dest));
  if (got !== want) throw new Error(`${file}: sha256 ${got}, expected ${want} (delete it to re-download)`);
  return dest;
}

const WORD_RE = /^[a-z]+$/;
const keep = (w) => WORD_RE.test(w) && w.length >= MIN_LEN && w.length <= MAX_LEN && !isBlocked(w);

function readScowl(tarball) {
  const members = [];
  for (const n of SCOWL_SIZES) for (const k of ["english", "american"]) {
    members.push(`scowl-${SCOWL_VERSION}/final/${k}-words.${n}`);
  }
  const dir = path.join(CACHE, "scowl");
  if (!members.every((m) => fs.existsSync(path.join(dir, m)))) {
    fs.mkdirSync(dir, { recursive: true });
    execFileSync("tar", ["-xzf", tarball, "-C", dir, ...members]);
  }
  const bySize = new Map(); // word -> smallest SCOWL size
  for (const n of SCOWL_SIZES) for (const k of ["english", "american"]) {
    // SCOWL files are ISO-8859-1; accented words fail WORD_RE anyway.
    const text = fs.readFileSync(path.join(dir, `scowl-${SCOWL_VERSION}/final/${k}-words.${n}`), "latin1");
    for (const line of text.split(/\r?\n/)) {
      const w = line.trim();
      if (keep(w) && !bySize.has(w)) bySize.set(w, n);
    }
  }
  return bySize;
}

/** Plain inflection of a shorter valid word: -s, -es, -ies, -ed, -ied, -ing. */
function isInflection(w, valid) {
  const has = (b) => valid.has(b);
  if (w.endsWith("ies") && has(w.slice(0, -3) + "y")) return true;
  if (w.endsWith("ied") && has(w.slice(0, -3) + "y")) return true;
  if (w.endsWith("es") && has(w.slice(0, -2))) return true;
  if (w.endsWith("s") && !w.endsWith("ss") && has(w.slice(0, -1))) return true;
  for (const suf of ["ed", "ing"]) {
    if (!w.endsWith(suf)) continue;
    const b = w.slice(0, -suf.length);
    if (has(b) || has(b + "e")) return true;
    if (b.length > 2 && b.at(-1) === b.at(-2) && has(b.slice(0, -1))) return true;
  }
  return false;
}

const pack = (words, len) => [...new Set(words)].filter((w) => w.length === len).sort().join("");

/** Emit a string literal split across lines of `perLine` words. */
function literal(packed, len, perLine = Math.max(8, Math.floor(96 / len))) {
  if (!packed) return '""';
  const step = len * perLine;
  const lines = [];
  for (let i = 0; i < packed.length; i += step) lines.push(JSON.stringify(packed.slice(i, i + step)));
  return lines.join(" +\n  ");
}

const HEADER = "// GENERATED by scripts/build-wordlists.mjs — do not edit. Sources: lib/games/words/SOURCES.md\n";
const gz = (s) => zlib.gzipSync(s, { level: 9 }).length;
const stats = [];

function writeModule(name, body) {
  const text = HEADER + body;
  fs.writeFileSync(path.join(OUT, name), text);
  stats.push({ name, bytes: Buffer.byteLength(text), gzip: gz(text) });
}

async function main() {
  fs.mkdirSync(CACHE, { recursive: true });
  fs.mkdirSync(OUT, { recursive: true });
  const scowl = readScowl(await fetchCached(SOURCES.scowl));
  const enableText = fs.readFileSync(await fetchCached(SOURCES.enable), "utf8");
  const enable = enableText.split(/\r?\n/).map((w) => w.trim()).filter(keep);

  const common = new Set([...scowl].filter(([, n]) => n <= COMMON_MAX).map(([w]) => w));
  const valid = new Set([...scowl].filter(([, n]) => n <= VALID_MAX).map(([w]) => w));

  const counts = [];
  for (let len = MIN_LEN; len <= MAX_LEN; len++) {
    const c = pack([...common], len);
    const e = pack([...valid].filter((w) => !common.has(w)), len);
    const name = `len${String(len).padStart(2, "0")}.ts`;
    writeModule(
      name,
      `/** ${len}-letter words, packed fixed-width and sorted (see ../packed.ts). */\n` +
        `export const LENGTH = ${len};\n` +
        `/** SCOWL size <= ${COMMON_MAX}: ${c.length / len} words. */\n` +
        `export const COMMON =\n  ${literal(c, len)};\n` +
        `/** SCOWL size ${COMMON_MAX + 1}-${VALID_MAX} (valid but not common): ${e.length / len} words. */\n` +
        `export const EXTRA =\n  ${literal(e, len)};\n`,
    );
    counts.push({ len, common: c.length / len, extra: e.length / len });
  }

  const answers = pack([...common].filter((w) => w.length === 5 && !isInflection(w, valid)), 5);
  const guessExtra = pack(enable.filter((w) => w.length === 5 && !valid.has(w)), 5);
  writeModule(
    "words5.ts",
    `/** Funzzle Word answers: common 5-letter words minus plain inflections (-s, -ed, -ing) — ${answers.length / 5} words. */\n` +
      `export const ANSWERS =\n  ${literal(answers, 5)};\n` +
      `/** Extra accepted guesses: ENABLE 5-letter words not in SCOWL <= ${VALID_MAX} — ${guessExtra.length / 5} words. */\n` +
      `export const GUESS_EXTRA =\n  ${literal(guessExtra, 5)};\n`,
  );

  console.table(counts);
  console.log(`answers5 ${answers.length / 5}, guess5 extra ${guessExtra.length / 5}`);
  console.log(`common ${common.size}, valid ${valid.size}`);
  console.table(stats);
  const total = stats.reduce((a, s) => ({ bytes: a.bytes + s.bytes, gzip: a.gzip + s.gzip }), { bytes: 0, gzip: 0 });
  console.log(`total ${total.bytes} bytes, ${total.gzip} gzip`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
