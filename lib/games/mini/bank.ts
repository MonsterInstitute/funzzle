/** The bank puzzle a date falls back to: a deterministic walk through the bank. */
export function bankMiniFor(date: string): BankMini {
  const day = Math.floor(Date.parse(`${date}T00:00:00Z`) / 86_400_000);
  // Step through the bank by a stride coprime with its size, so consecutive
  // days never repeat and the order isn't simply alphabetical.
  const n = MINI_BANK.length;
  const stride = [7, 11, 13, 17, 19, 23].find((s) => gcd(s, n) === 1) ?? 1;
  const offset = hashSeed("mini-crossword:bank") % n;
  return MINI_BANK[(((day * stride + offset) % n) + n) % n];
}

/** The practice puzzle for a seed (a pure function of the seed, so challenges replay it). */
export function bankMiniForSeed(seed: string): BankMini {
  return MINI_BANK[createRng(seed).int(MINI_BANK.length)];
}

function gcd(a: number, b: number): number {
  return b ? gcd(b, a % b) : a;
}
